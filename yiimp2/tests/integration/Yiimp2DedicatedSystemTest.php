    /**
     * Test: Scale stratum service → Verify multiple instances work
     * 
     * @test
     */
    public function testStratumServiceScaling()
    {
        // Verify docker-compose.yml supports scaling
        $composeFile = $this->projectRoot . '/docker-compose.yml';
        $composeContent = file_get_contents($composeFile);
        
        // Step 1: Verify multiple stratum services are defined
        $stratumServices = [];
        if (preg_match_all('/yiimp2-stratum-(\w+):/m', $composeContent, $matches)) {
            $stratumServices = $matches[1];
        }
        
        $this->assertGreaterThan(1, count($stratumServices), 
            'Multiple stratum services should be defined for different algorithms');
        
        // Step 2: Verify each stratum service has unique port mapping
        $ports = [];
        foreach ($stratumServices as $algo) {
            if (preg_match("/yiimp2-stratum-$algo:.*?ports:.*?\"(\d+):/s", $composeContent, $matches)) {
                $port = $matches[1];
                $this->assertNotContains($port, $ports, 
                    "Port $port is used by multiple stratum services");
                $ports[] = $port;
            }
        }
        
        // Step 3: Verify all ports are in 4000+ range (yiimp2 dedicated)
        foreach ($ports as $port) {
            $this->assertGreaterThanOrEqual(4000, (int)$port,
                "Stratum port $port should be in 4000+ range for yiimp2");
            $this->assertLessThan(5000, (int)$port,
                "Stratum port $port should be below 5000");
        }
    }
    
    /**
     * Test: Restart individual service → Verify others unaffected
     * 
     * @test
     */
    public function testServiceFaultIsolation()
    {
        // Verify docker-compose.yml has proper service dependencies
        $composeFile = $this->projectRoot . '/docker-compose.yml';
        $composeContent = file_get_contents($composeFile);
        
        // Step 1: Verify services have restart policies
        $this->assertStringContainsString('restart:', $composeContent,
            'Services should have restart policies defined');
        
        // Step 2: Verify services depend on database but not on each other
        // Stratum services should not depend on web service
        $stratumSection = $this->extractServiceSection($composeContent, 'yiimp2-stratum-sha256');
        if ($stratumSection) {
            $this->assertStringContainsString('yiimp2-db', $stratumSection,
                'Stratum should depend on database');
            $this->assertStringNotContainsString('yiimp2-web', $stratumSection,
                'Stratum should not depend on web service');
        }
        
        // Step 3: Verify backend services don't depend on stratum
        $backendSection = $this->extractServiceSection($composeContent, 'yiimp2-backend-main');
        if ($backendSection) {
            $this->assertStringContainsString('yiimp2-db', $backendSection,
                'Backend should depend on database');
            $this->assertStringNotContainsString('yiimp2-stratum', $backendSection,
                'Backend should not depend on stratum services');
        }
    }
    
    // Helper methods
    
    private function getDbConnection()
    {
        try {
            $dsn = "mysql:host=127.0.0.1";
            $pdo = new \PDO($dsn, 'root', '', [
                \PDO::ATTR_ERRMODE => \PDO::ERRMODE_EXCEPTION
            ]);
            return $pdo;
        } catch (\PDOException $e) {
            return null;
        }
    }
    
    private function cleanupTestDatabase()
    {
        try {
            $pdo = $this->getDbConnection();
            if ($pdo) {
                $pdo->exec("DROP DATABASE IF EXISTS `{$this->testDbName}`");
            }
        } catch (\PDOException $e) {
            // Ignore errors during cleanup
        }
    }
    
    private function createTestDatabase()
    {
        try {
            $pdo = $this->getDbConnection();
            if (!$pdo) {
                return false;
            }
            $pdo->exec("CREATE DATABASE IF NOT EXISTS `{$this->testDbName}`");
            return true;
        } catch (\PDOException $e) {
            return false;
        }
    }
    
    private function importSchema()
    {
        try {
            $pdo = $this->getDbConnection();
            if (!$pdo) {
                return false;
            }
            
            $pdo->exec("USE `{$this->testDbName}`");
            
            $sql = file_get_contents($this->schemaFile);
            if ($sql === false) {
                return false;
            }
            
            // Split by semicolons and execute each statement
            $statements = array_filter(
                array_map('trim', explode(';', $sql)),
                function($stmt) { return !empty($stmt); }
            );
            
            foreach ($statements as $statement) {
                if (!empty($statement)) {
                    $pdo->exec($statement);
                }
            }
            
            return true;
        } catch (\PDOException $e) {
            return false;
        }
    }
    
    private function tableExists($tableName)
    {
        try {
            $pdo = $this->getDbConnection();
            if (!$pdo) {
                return false;
            }
            
            $pdo->exec("USE `{$this->testDbName}`");
            $stmt = $pdo->query("SHOW TABLES LIKE '{$tableName}'");
            return $stmt->rowCount() > 0;
        } catch (\PDOException $e) {
            return false;
        }
    }
    
    private function columnExists($tableName, $columnName)
    {
        try {
            $pdo = $this->getDbConnection();
            if (!$pdo) {
                return false;
            }
            
            $pdo->exec("USE `{$this->testDbName}`");
            $stmt = $pdo->query("SHOW COLUMNS FROM `{$tableName}` LIKE '{$columnName}'");
            return $stmt->rowCount() > 0;
        } catch (\PDOException $e) {
            return false;
        }
    }
    
    private function runDataMigration()
    {
        // This would run the actual migration script
        // For testing purposes, we'll verify the script exists
        return file_exists('bin/migrate-yiimp2-data.sh');
    }
    
    private function getRecordCount($tableName)
    {
        try {
            $pdo = $this->getDbConnection();
            if (!$pdo) {
                return 0;
            }
            
            $pdo->exec("USE `{$this->testDbName}`");
            $stmt = $pdo->query("SELECT COUNT(*) FROM `{$tableName}`");
            return (int)$stmt->fetchColumn();
        } catch (\PDOException $e) {
            return 0;
        }
    }
    
    private function getInvalidForeignKeys()
    {
        $command = sprintf(
            'mysql -u root %s -e "SELECT c.id FROM coins c LEFT JOIN algos a ON c.algo = a.name WHERE a.id IS NULL" -s -N',
            escapeshellarg($this->testDbName)
        );
        exec($command, $output, $returnCode);
        return $returnCode === 0 ? $output : [];
    }
    
    private function isDockerAvailable()
    {
        exec('docker --version 2>&1', $output, $returnCode);
        return $returnCode === 0;
    }
    
    private function extractServiceSection($composeContent, $serviceName)
    {
        // Extract the section for a specific service
        $pattern = "/  $serviceName:.*?(?=\n  \w+:|$)/s";
        if (preg_match($pattern, $composeContent, $matches)) {
            return $matches[0];
        }
        return null;
    }
}
