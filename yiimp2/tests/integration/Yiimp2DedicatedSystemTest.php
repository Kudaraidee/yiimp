<?php

namespace tests\integration;

use Codeception\Test\Unit;

/**
 * Integration tests for Yiimp2 Dedicated System
 * 
 * Tests end-to-end workflows for the complete Yiimp2 dedicated system setup:
 * - Schema generation and import
 * - Data migration and validation
 * - Docker Compose deployment
 * - Stratum server connectivity
 * - Backend script database isolation
 * - Service scaling and fault isolation
 * 
 * Requirements: All requirements from yiimp2-dedicated-system spec
 */
class Yiimp2DedicatedSystemTest extends Unit
{
    private $testDbName = 'yiimp2_integration_test';
    private $projectRoot;
    private $schemaFile;
    private $oldYiimpFile;
    
    protected function _before()
    {
        // Project root is one level up from yiimp2/
        // __DIR__ is yiimp2/tests/integration, so we need to go up 3 levels
        $this->projectRoot = dirname(__DIR__, 3);
        $this->schemaFile = $this->projectRoot . '/sql/yiimp2-init.sql';
        $this->oldYiimpFile = $this->projectRoot . '/sql/old-yiimp.sql';
        
        // Clean up any previous test database
        $this->cleanupTestDatabase();
    }
    
    protected function _after()
    {
        // Clean up test database
        $this->cleanupTestDatabase();
    }
    
    /**
     * Test: Generate schema → Import → Verify tables exist
     * 
     * @test
     */
    public function testSchemaGenerationAndImport()
    {
        // Step 1: Verify schema file exists (should be generated by bin/generate-yiimp2-schema.sh)
        if (!file_exists($this->schemaFile)) {
            $this->markTestSkipped('Schema file does not exist. Run bin/generate-yiimp2-schema.sh first.');
        }
        
        // Step 2: Create test database
        if (!$this->createTestDatabase()) {
            $this->markTestSkipped('Cannot create test database. Database connection not available.');
        }
        
        // Step 3: Import schema
        $importResult = $this->importSchema();
        if (!$importResult) {
            $this->markTestSkipped('Failed to import schema. Database may not be accessible.');
        }
        $this->assertTrue($importResult, 'Failed to import schema');
        
        // Step 4: Verify all required tables exist
        $requiredTables = [
            'coins', 'algos', 'settings', 'shares', 'workers', 'accounts',
            'blocks', 'payouts', 'earnings', 'hashrate', 'hashuser',
            'stratums', 'markets', 'benchmarks'
        ];
        
        foreach ($requiredTables as $table) {
            $exists = $this->tableExists($table);
            $this->assertTrue($exists, "Table '$table' does not exist after schema import");
        }
        
        // Step 5: Verify decimal column exists in coins table
        $hasDecimalColumn = $this->columnExists('coins', 'decimal');
        $this->assertTrue($hasDecimalColumn, 'Decimal column missing from coins table');
    }
    
    /**
     * Test: Extract data → Migrate → Validate counts match
     * 
     * @test
     */
    public function testDataMigrationAndValidation()
    {
        // Skip if old-yiimp.sql doesn't exist
        if (!file_exists($this->oldYiimpFile)) {
            $this->markTestSkipped('old-yiimp.sql not found. This test requires source data.');
        }
        
        // Skip if schema file doesn't exist
        if (!file_exists($this->schemaFile)) {
            $this->markTestSkipped('Schema file does not exist. Run bin/generate-yiimp2-schema.sh first.');
        }
        
        // Step 1: Create and initialize test database
        if (!$this->createTestDatabase()) {
            $this->markTestSkipped('Cannot create test database. Database connection not available.');
        }
        if (!$this->importSchema()) {
            $this->markTestSkipped('Failed to import schema. Database may not be accessible.');
        }
        
        // Step 2: Run data migration script
        $migrationResult = $this->runDataMigration();
        if (!$migrationResult) {
            $this->markTestSkipped('Data migration failed. Migration script may not be available.');
        }
        $this->assertTrue($migrationResult, 'Data migration failed');
        
        // Step 3: Verify configuration tables are populated
        $coinsCount = $this->getRecordCount('coins');
        $algosCount = $this->getRecordCount('algos');
        $settingsCount = $this->getRecordCount('settings');
        
        $this->assertGreaterThan(0, $coinsCount, 'No coins migrated');
        $this->assertGreaterThan(0, $algosCount, 'No algorithms migrated');
        $this->assertGreaterThan(0, $settingsCount, 'No settings migrated');
        
        // Step 4: Verify operational tables are empty
        $operationalTables = ['shares', 'workers', 'accounts', 'blocks', 'payouts', 'earnings'];
        foreach ($operationalTables as $table) {
            $count = $this->getRecordCount($table);
            $this->assertEquals(0, $count, "Operational table '$table' should be empty but has $count records");
        }
        
        // Step 5: Verify foreign key integrity (coins reference algos)
        $invalidCoins = $this->getInvalidForeignKeys();
        $this->assertEquals(0, count($invalidCoins), 'Found coins with invalid algorithm references');
    }
    
    /**
     * Test: Generate configs → docker compose up → Verify all services running
     * 
     * @test
     */
    public function testDockerComposeDeployment()
    {
        // Step 1: Verify docker-compose.yml exists
        $composeFile = $this->projectRoot . '/docker-compose.yml';
        $this->assertFileExists($composeFile, 'docker-compose.yml not found');
        
