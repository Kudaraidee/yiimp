    }
    
    /**
     * Test: Submit share to stratum → Verify written to yiimp2 database
     * 
     * @test
     */
    public function testStratumDatabaseIsolation()
    {
        // This test requires a running stratum server
        // We'll verify the configuration is correct for database isolation
        
        // Step 1: Verify stratum config files point to yiimp2 database
        $stratumConfigs = glob($this->projectRoot . '/config/yiimp2/stratum/*.conf');
        $this->assertGreaterThan(0, count($stratumConfigs), 'No stratum configs found');
        
        foreach ($stratumConfigs as $configFile) {
            $content = file_get_contents($configFile);
            
            // Verify database name is yiimp2 (not yiimp)
            $this->assertStringContainsString('database = yiimp2', $content, 
                "Config $configFile does not specify yiimp2 database");
            
            // Verify it doesn't reference legacy database (check for exact match "database = yiimp\n" to avoid matching "yiimp2")
            $legacyDbPattern = '/database\s*=\s*yiimp\s*$/m';
            $this->assertDoesNotMatchRegularExpression($legacyDbPattern, $content,
                "Config $configFile references legacy yiimp database");
        }
        
        // Step 2: Verify port isolation (yiimp2 uses 4000+ range)
        foreach ($stratumConfigs as $configFile) {
            $content = file_get_contents($configFile);
            
            // Extract port number
            if (preg_match('/port = (\d+)/', $content, $matches)) {
                $port = (int)$matches[1];
                
                // Internal port should be 3333 (Docker maps to 4000+)
                $this->assertEquals(3333, $port, 
                    "Config $configFile should use internal port 3333 (Docker maps to external 4000+)");
            }
        }
    }
    
