    /**
     * Test that AJAX URLs work with relative and absolute formats
     */
    public function testAjaxUrlsWorkWithDifferentFormats()
    {
        $route = 'admin/user-results';
        $urlManager = Yii::$app->urlManager;
        
        // Test absolute URL generation
        $absoluteUrl = $urlManager->createAbsoluteUrl([$route]);
        $this->assertNotEmpty($absoluteUrl);
        
        // Verify no underscores in path
        $absolutePath = parse_url($absoluteUrl, PHP_URL_PATH);
        if ($absolutePath) {
            $this->assertStringNotContainsString('_', $absolutePath,
                "Absolute URL path should not contain underscores");
        }
        
        // Verify the route is in the URL
        $this->assertStringContainsString('user-results', $absoluteUrl,
            "URL should contain the hyphenated action name");
    }

    /**
     * Test AJAX URL generation matches configured routes
     * 
     * Verifies that generated URLs align with urlManager rules
     */
    public function testAjaxUrlsMatchConfiguredRoutes()
    {
        $urlManager = Yii::$app->urlManager;
        
        // Get configured rules
        $rules = $urlManager->rules;
        
        // Test that admin routes follow the pattern
        $adminRoutes = [
            'admin/user-results',
            'admin/worker-results',
            'admin/payments-results',
        ];

        foreach ($adminRoutes as $route) {
            $url = $urlManager->createAbsoluteUrl([$route]);
            
            // Verify URL follows admin/<action> pattern
            $this->assertMatchesRegularExpression(
                '#/admin/[a-z-]+#',
                $url,
                "Admin AJAX URL should follow admin/<action> pattern: {$url}"
            );
            
            // Verify no underscores
            $this->assertDoesNotMatchRegularExpression(
                '#_#',
                parse_url($url, PHP_URL_PATH),
                "Admin AJAX URL should not contain underscores: {$url}"
            );
        }
    }

    /**
     * Test that AJAX URLs handle special characters properly
     */
    public function testAjaxUrlsHandleSpecialCharactersInParameters()
    {
        $route = 'admin/user-results';
        $specialParams = [
            'search' => 'test@example.com',
            'filter' => 'value with spaces',
        ];

        $urlManager = Yii::$app->urlManager;
        $url = $urlManager->createAbsoluteUrl(array_merge([$route], $specialParams));
        
        // Verify URL is generated
        $this->assertNotEmpty($url);
        
        // Verify path doesn't contain underscores
        $urlPath = parse_url($url, PHP_URL_PATH);
        $this->assertStringNotContainsString('_', $urlPath);
        
        // Verify query string is properly encoded
        $urlParts = parse_url($url);
        if (isset($urlParts['query'])) {
            parse_str($urlParts['query'], $queryParams);
            
            // Verify parameters are preserved
            $this->assertArrayHasKey('search', $queryParams);
            $this->assertArrayHasKey('filter', $queryParams);
        }
    }
}
