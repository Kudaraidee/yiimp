    /**
     * Test AJAX URL generation with query parameters
     * 
     * Verifies that AJAX URLs with parameters are properly formatted
     * 
     * @dataProvider ajaxUrlWithParamsProvider
     */
    public function testAjaxUrlsWithQueryParameters($route, $params, $expectedKeys)
    {
        // Generate URL with parameters
        $urlManager = Yii::$app->urlManager;
        $generatedUrl = $urlManager->createAbsoluteUrl(array_merge([$route], $params));
        
        // Verify URL was generated
        $this->assertNotEmpty($generatedUrl,
            "URL should be generated for route with params: {$route}");
        
        // Parse URL to check query string
        $urlParts = parse_url($generatedUrl);
        
        // Verify no underscores in the path
        if (isset($urlParts['path'])) {
            $this->assertStringNotContainsString('_', $urlParts['path'],
                "URL path should not contain underscores: {$generatedUrl}");
        }
        
        // Verify query parameters are present
        if (!empty($params) && isset($urlParts['query'])) {
            parse_str($urlParts['query'], $queryParams);
            
            foreach ($expectedKeys as $key) {
                $this->assertArrayHasKey($key, $queryParams,
                    "Query parameters should include '{$key}': {$generatedUrl}");
            }
        }
    }

