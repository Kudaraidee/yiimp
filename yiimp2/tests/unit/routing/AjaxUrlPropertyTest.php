    /**
     * Test that AJAX URLs are consistent with view usage
     * 
     * Simulates how views generate AJAX URLs and verifies consistency
     */
    public function testAjaxUrlConsistencyWithViewUsage()
    {
        $testCases = [
            ['admin/user-results', []],
            ['admin/worker-results', ['algo' => 'sha256']],
            ['admin/payments-results', ['status' => 'pending']],
        ];

        $urlManager = Yii::$app->urlManager;
        foreach ($testCases as list($route, $params)) {
            // Generate URL as a view would
            $url1 = $urlManager->createAbsoluteUrl(array_merge([$route], $params));
            
            // Generate again to verify consistency
            $url2 = $urlManager->createAbsoluteUrl(array_merge([$route], $params));
            
            $this->assertEquals($url1, $url2,
                "AJAX URL generation should be consistent for route: {$route}");
            
            // Verify hyphenated format
            $urlPath = parse_url($url1, PHP_URL_PATH);
            $this->assertStringNotContainsString('_', $urlPath,
                "AJAX URL should use hyphens: {$url1}");
        }
    }

    /**
     * Test AJAX URL generation for all admin result endpoints
     * 
     * Verifies that all *-results endpoints generate valid URLs
     * 
     * @dataProvider adminResultEndpointProvider
     */
    public function testAllAdminResultEndpointsGenerateValidUrls($endpoint)
    {
        $urlManager = Yii::$app->urlManager;
        $url = $urlManager->createAbsoluteUrl(['admin/' . $endpoint]);
        
        // Verify URL is generated
        $this->assertNotEmpty($url,
            "URL should be generated for endpoint: {$endpoint}");
        
        // Verify no underscores
        $urlPath = parse_url($url, PHP_URL_PATH);
        $this->assertStringNotContainsString('_', $urlPath,
            "Endpoint URL should not contain underscores: {$url}");
        
        // Verify it ends with -results
        $this->assertStringEndsWith('-results', $endpoint,
            "Result endpoint should end with '-results': {$endpoint}");
        
        // Verify the URL contains the endpoint
        $this->assertStringContainsString($endpoint, $url,
            "URL should contain the endpoint name: {$url}");
    }

