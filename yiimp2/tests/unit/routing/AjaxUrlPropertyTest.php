<?php

namespace tests\unit\routing;

use Codeception\Test\Unit;
use Yii;
use yii\helpers\Url;

/**
 * Property-based tests for AJAX URL generation
 * 
 * **Feature: yiimp2-admin-panel-fixes, Property 9: AJAX URLs match route patterns**
 * **Validates: Requirements 6.2**
 */
class AjaxUrlPropertyTest extends Unit
{
    /**
     * @var \UnitTester
     */
    protected $tester;

    protected function _before()
    {
        parent::_before();
        // Ensure URL manager is properly configured
        Yii::$app->urlManager->enablePrettyUrl = true;
        Yii::$app->urlManager->showScriptName = false;
    }

    /**
     * Property 9: AJAX URLs match route patterns
     * 
     * For any AJAX request generated by a view, the URL should follow the hyphenated
     * convention and successfully reach the intended controller action.
     * 
     * This test verifies that:
     * 1. AJAX URLs are generated using Url::to() helper
     * 2. Generated URLs use hyphens instead of underscores
     * 3. URLs match the configured route patterns
     * 4. URLs are properly formatted for AJAX requests
     * 
     * @dataProvider ajaxEndpointProvider
     */
    public function testAjaxUrlsMatchRoutePatterns($controller, $action, $expectedPattern)
    {
        // Generate AJAX URL using URL manager
        $route = $controller . '/' . $action;
        $urlManager = Yii::$app->urlManager;
        $generatedUrl = $urlManager->createAbsoluteUrl([$route]);
        
        // Verify the URL was generated
        $this->assertNotEmpty($generatedUrl, 
            "URL should be generated for route: {$route}");
        
        // Verify no underscores in the URL path
        $urlPath = parse_url($generatedUrl, PHP_URL_PATH);
        $this->assertStringNotContainsString('_', $urlPath,
            "AJAX URL should not contain underscores: {$generatedUrl}");
        
        // Verify the URL matches the expected pattern
        $this->assertStringContainsString($expectedPattern, $generatedUrl,
            "AJAX URL should match pattern '{$expectedPattern}': {$generatedUrl}");
        
        // Verify the URL contains the expected pattern (may have test environment prefix)
        $this->assertStringContainsString($expectedPattern, $generatedUrl,
            "AJAX URL should contain expected pattern: {$generatedUrl}");
    }

