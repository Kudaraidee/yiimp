    /**
     * Test that CSRF token persists across multiple requests in same session
     * 
     * This verifies that the token remains consistent within a session,
     * which is critical for form submissions.
     * 
     * @test
     */
    public function testCsrfTokenPersistenceInSession()
    {
        $iterations = 50;
        $failures = [];
        
        for ($i = 0; $i < $iterations; $i++) {
            // Start fresh session
            if (Yii::$app->session->getIsActive()) {
                Yii::$app->session->destroy();
            }
            
            Yii::$app->session->open();
            
            // Get initial token
            $initialToken = Yii::$app->request->getCsrfToken();
            
            // Simulate multiple requests in same session
            $requestCount = rand(3, 10);
            $tokens = [$initialToken];
            
            for ($j = 0; $j < $requestCount; $j++) {
                $token = Yii::$app->request->getCsrfToken();
                $tokens[] = $token;
                
                // Verify token is not null
                if ($token === null || empty($token)) {
                    $failures[] = [
                        'iteration' => $i,
                        'request' => $j,
                        'reason' => 'Token became null/empty during session',
                    ];
                }
            }
            
            // Verify all tokens are the same (consistency within session)
            $uniqueTokens = array_unique($tokens);
            if (count($uniqueTokens) !== 1) {
                $failures[] = [
                    'iteration' => $i,
                    'reason' => 'Token changed within same session',
                    'unique_token_count' => count($uniqueTokens),
                    'request_count' => $requestCount + 1,
                ];
            }
            
            Yii::$app->session->close();
        }
        
        if (!empty($failures)) {
            $this->fail(
                "Token persistence test failed in " . count($failures) . " out of $iterations iterations:\n" .
                json_encode(array_slice($failures, 0, 5), JSON_PRETTY_PRINT)
            );
        }
        
        $this->assertTrue(true, "CSRF token persists correctly across requests in all $iterations sessions");
    }
    
    /**
     * Test CSRF token storage with different session backends
     * 
     * Verifies that token storage works correctly regardless of session backend
     * (CacheSession, FileSession, etc.)
     * 
     * @test
     */
    public function testCsrfTokenStorageAcrossSessionBackends()
    {
        $backends = [
            'CacheSession' => [
                'class' => 'yii\web\CacheSession',
                'cache' => 'cache',
            ],
            'FileSession' => [
                'class' => 'yii\web\Session',
            ],
        ];
        
        $failures = [];
        $iterationsPerBackend = 25;
        
        foreach ($backends as $backendName => $config) {
            for ($i = 0; $i < $iterationsPerBackend; $i++) {
                // Configure session backend
                if (Yii::$app->session->getIsActive()) {
                    Yii::$app->session->destroy();
                }
                
                $config['name'] = 'TEST_' . rand(1000, 9999);
                $config['timeout'] = 3600;
                
                Yii::$app->set('session', $config);
                
                try {
                    Yii::$app->session->open();
                    
                    // Generate and verify token
                    $token = Yii::$app->request->getCsrfToken();
                    
                    if (empty($token)) {
                        $failures[] = [
                            'backend' => $backendName,
                            'iteration' => $i,
                            'reason' => 'Failed to generate token',
                        ];
                        continue;
                    }
                    
                    // Verify token can be retrieved again (which proves it's stored)
                    $retrievedToken = Yii::$app->request->getCsrfToken();
                    
                    if (empty($retrievedToken)) {
                        $failures[] = [
                            'backend' => $backendName,
                            'iteration' => $i,
                            'reason' => 'Failed to retrieve token from storage',
                        ];
                        continue;
                    }
                    
                    // Verify tokens are consistent (proves storage is working)
                    if ($token !== $retrievedToken) {
                        $failures[] = [
                            'backend' => $backendName,
                            'iteration' => $i,
                            'reason' => 'Token inconsistency indicates storage issue',
                            'original' => substr($token, 0, 20) . '...',
                            'retrieved' => substr($retrievedToken, 0, 20) . '...',
                        ];
                    }
                    
                    Yii::$app->session->close();
                } catch (\Exception $e) {
                    $failures[] = [
                        'backend' => $backendName,
                        'iteration' => $i,
                        'reason' => 'Exception during test',
                        'error' => $e->getMessage(),
                    ];
                }
            }
        }
        
        if (!empty($failures)) {
            $failuresByBackend = [];
            foreach ($failures as $failure) {
                $backend = $failure['backend'];
                if (!isset($failuresByBackend[$backend])) {
                    $failuresByBackend[$backend] = 0;
                }
                $failuresByBackend[$backend]++;
            }
            
            $this->fail(
                "Backend compatibility test failed in " . count($failures) . " iterations:\n" .
                "Failures by backend: " . json_encode($failuresByBackend, JSON_PRETTY_PRINT) . "\n" .
                "Sample failures:\n" . json_encode(array_slice($failures, 0, 3), JSON_PRETTY_PRINT)
            );
        }
        
        $totalIterations = count($backends) * $iterationsPerBackend;
        $this->assertTrue(
            true,
            "CSRF token storage works correctly across all backends in $totalIterations iterations"
        );
    }
}
