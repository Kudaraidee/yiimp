#!/bin/bash

# Configuration Generation Script for Yiimp2 Dedicated System
# Generates serverconfig.php and stratum configuration files for yiimp2

set -e

# Default values
DB_NAME="yiimp2"
DB_USER="yiimp2"
DB_PASS=""
DB_HOST="yiimp2-db"  # Docker service name
PORT_OFFSET=1000
LEGACY_STRATUM_DIR="config/stratum"
YIIMP2_CONFIG_DIR="config/yiimp2"
YIIMP2_STRATUM_DIR="${YIIMP2_CONFIG_DIR}/stratum"
LOG_FILE="log/yiimp2-config-generation.log"
START_TIME=$(date +%s)

# Create log directory if it doesn't exist
mkdir -p "$(dirname "$LOG_FILE")"

# Initialize log file with header
cat > "$LOG_FILE" << EOF
================================================================================
Yiimp2 Configuration Generation Log
================================================================================
Start Time: $(date)
================================================================================

EOF

# Logging functions that write to both console and log file
log_info() {
    local timestamp=$(date '+%Y-%m-%d %H:%M:%S')
    echo "$1"
    echo "[$timestamp] [INFO] $1" >> "$LOG_FILE"
}

log_warn() {
    local timestamp=$(date '+%Y-%m-%d %H:%M:%S')
    echo "Warning: $1"
    echo "[$timestamp] [WARN] $1" >> "$LOG_FILE"
}

log_error() {
    local timestamp=$(date '+%Y-%m-%d %H:%M:%S')
    echo "Error: $1"
    echo "[$timestamp] [ERROR] $1" >> "$LOG_FILE"
}

log_debug() {
    local timestamp=$(date '+%Y-%m-%d %H:%M:%S')
    echo "[$timestamp] [DEBUG] $1" >> "$LOG_FILE"
}

# Parse command-line arguments
while [[ $# -gt 0 ]]; do
    case $1 in
        --db-name)
            DB_NAME="$2"
            shift 2
            ;;
        --db-user)
            DB_USER="$2"
            shift 2
            ;;
        --db-pass)
            DB_PASS="$2"
            shift 2
            ;;
        --db-host)
            DB_HOST="$2"
            shift 2
            ;;
        --port-offset)
            PORT_OFFSET="$2"
            shift 2
            ;;
        --help)
            echo "Usage: $0 [OPTIONS]"
            echo ""
            echo "Options:"
            echo "  --db-name NAME       Database name (default: yiimp2)"
            echo "  --db-user USER       Database user (default: yiimp2)"
            echo "  --db-pass PASS       Database password (required)"
            echo "  --db-host HOST       Database host (default: yiimp2-db)"
            echo "  --port-offset NUM    Port offset from legacy ports (default: 1000)"
            echo "  --help               Show this help message"
            exit 0
            ;;
        *)
            echo "Unknown option: $1"
            echo "Use --help for usage information"
            exit 1
            ;;
    esac
done

# Validate required parameters
log_info "Validating configuration parameters..."
if [ -z "$DB_PASS" ]; then
    log_error "--db-pass is required"
    exit 1
fi

log_info "Configuration parameters:"
log_info "  Database name: $DB_NAME"
log_info "  Database user: $DB_USER"
log_info "  Database host: $DB_HOST"
log_info "  Port offset: $PORT_OFFSET"
log_info "  Legacy stratum dir: $LEGACY_STRATUM_DIR"
log_info "  Yiimp2 config dir: $YIIMP2_CONFIG_DIR"
log_info "  Log file: $LOG_FILE"

# Create yiimp2 config directories
log_info "Creating yiimp2 configuration directories..."
mkdir -p "$YIIMP2_CONFIG_DIR"
mkdir -p "$YIIMP2_STRATUM_DIR"
log_info "✓ Directories created successfully"

# Generate serverconfig.php
log_info "Generating ${YIIMP2_CONFIG_DIR}/serverconfig.php..."
cat > "${YIIMP2_CONFIG_DIR}/serverconfig.php" << EOF
<?php
/**
 * Yiimp2 Dedicated System Configuration
 * Generated by generate-yiimp2-configs.sh
 * 
 * This configuration is for the Yiimp2 dedicated system running in Docker containers.
 * It uses a separate database (${DB_NAME}) and is completely independent from legacy Yiimp.
 */

ini_set('date.timezone', 'UTC');

define('YAAMP_LOGS', '/var/log/yiimp2');
define('YAAMP_HTDOCS', '/var/yiimp2');
define('YAAMP_BIN', '/var/yiimp2/bin');

// Yiimp2 Dedicated Database Configuration
define('YAAMP_DBHOST', '${DB_HOST}');
define('YAAMP_DBNAME', '${DB_NAME}');
define('YAAMP_DBUSER', '${DB_USER}');
define('YAAMP_DBPASSWORD', '${DB_PASS}');

define('YAAMP_SITE_URL', 'localhost:8090');
define('YAAMP_STRATUM_URL', YAAMP_SITE_URL);
define('YAAMP_SITE_NAME', 'Yiimp2 Mining Pool');

define('YAAMP_PRODUCTION', false);

define('YIIMP_PUBLIC_EXPLORER', true);
define('YIIMP_PUBLIC_BENCHMARK', false);

define('YAAMP_RENTAL', false);
define('YAAMP_LIMIT_ESTIMATE', false);

define('YAAMP_FEES_SOLO', 1);
define('YAAMP_FEES_MINING', 0.5);
define('YAAMP_FEES_EXCHANGE', 2);
define('YAAMP_FEES_RENTING', 2);
define('YAAMP_TXFEE_RENTING_WD', 0.002);
define('YAAMP_PAYMENTS_FREQ', 3*60*60);
define('YAAMP_PAYMENTS_MINI', 0.1);

define('YAAMP_ALLOW_EXCHANGE', false);
define('YIIMP_FIAT_ALTERNATIVE', 'EUR');

define('YAAMP_USE_NICEHASH_API', false);

define('YAAMP_BTCADDRESS', '');

define('YIIMP_ADMIN_LOGIN', true);
define('YAAMP_ADMIN_EMAIL', 'admin@localhost');
define('YAAMP_ADMIN_USER', 'admin');
define('YAAMP_ADMIN_PASS', 'changeme');
define('YAAMP_ADMIN_IP', '127.0.0.1');
define('YAAMP_ADMIN_WEBCONSOLE', true);
define('YAAMP_CREATE_NEW_COINS', false);
define('YAAMP_NOTIFY_NEW_COINS', false);
define('YAAMP_DEFAULT_ALGO', 'sha256');

define('GITHUB_ACCESSTOKEN', '');

define('SMTP_HOST', '');
define('SMTP_PORT', 25);
define('SMTP_USEAUTH', false);
define('SMTP_USERNAME', '');
define('SMTP_PASSWORD', '');
define('SMTP_DEFAULT_FROM', '');
define('SMTP_DEFAULT_HELO', '');

define('YAAMP_USE_NGINX', false);

define('YIIMP_MYSQLDUMP_USER', '${DB_USER}');
define('YIIMP_MYSQLDUMP_PASS', '${DB_PASS}');

// Exchange keys (empty for dedicated system)
define('EXCH_BINANCE_KEY', '');
define('EXCH_BINANCE_SECRET', '');
define('EXCH_CEXIO_SECRET', '');
define('EXCH_EXBITRON_KEY', '');
define('EXCH_HITBTC_SECRET', '');
define('EXCH_HITBTC_KEY','');
define('EXCH_KRAKEN_KEY', '');
define('EXCH_KRAKEN_SECRET','');
define('EXCH_KUCOIN_SECRET', '');
define('EXCH_POLONIEX_KEY', '');
define('EXCH_POLONIEX_SECRET', '');
define('EXCH_SAFETRADE_KEY', '');
define('EXCH_SAFETRADE_SECRET', '');
define('EXCH_TRADEOGRE_KEY', '');
define('EXCH_TRADEOGRE_SECRET', '');
define('EXCH_YOBIT_KEY', '');
define('EXCH_YOBIT_SECRET', '');
define('EXCH_NONKYC_KEY', '');
define('EXCH_NONKYC_SECRET', '');
define('EXCH_XEGGEX_KEY', '');
define('EXCH_XEGGEX_SECRET', '');

define('EXCH_AUTO_WITHDRAW', 0);

define('NICEHASH_API_KEY','');
define('NICEHASH_API_ID','');
define('NICEHASH_DEPOSIT','');
define('NICEHASH_DEPOSIT_AMOUNT','0');

\$cold_wallet_table = array();

\$configFixedPoolFees = array();
\$configFixedPoolFeesSolo = array();
\$configCustomPorts = array();
\$configAlgoNormCoef = array();

EOF

# Set secure permissions for serverconfig.php (contains passwords)
chmod 600 "${YIIMP2_CONFIG_DIR}/serverconfig.php"
log_info "✓ serverconfig.php generated successfully"
log_info "  - Set permissions to 600 (read/write for owner only)"

# Generate stratum configuration files
log_info "Generating stratum configuration files..."

if [ ! -d "$LEGACY_STRATUM_DIR" ]; then
    log_warn "Legacy stratum directory not found: $LEGACY_STRATUM_DIR"
    log_warn "No stratum configurations will be generated."
else
    LEGACY_CONFIG_COUNT=$(find "$LEGACY_STRATUM_DIR" -maxdepth 1 -name "*.conf" -type f | wc -l)
    log_info "Found $LEGACY_CONFIG_COUNT legacy stratum configuration(s)"
    # Process each legacy stratum config file
    STRATUM_COUNTER=0
    for legacy_config in "$LEGACY_STRATUM_DIR"/*.conf; do
        if [ ! -f "$legacy_config" ]; then
            continue
        fi
        
        STRATUM_COUNTER=$((STRATUM_COUNTER + 1))
        filename=$(basename "$legacy_config")
        yiimp2_config="${YIIMP2_STRATUM_DIR}/${filename}"
        
        log_info "[$STRATUM_COUNTER/$LEGACY_CONFIG_COUNT] Processing $filename..."
        
        # Extract values from legacy config
        legacy_port=$(grep "^port = " "$legacy_config" | head -1 | awk '{print $3}')
        legacy_algo=$(grep "^algo = " "$legacy_config" | head -1 | awk '{print $3}')
        legacy_difficulty=$(grep "^difficulty = " "$legacy_config" | head -1 | awk '{print $3}')
        legacy_max_ttf=$(grep "^max_ttf = " "$legacy_config" | head -1 | awk '{print $3}')
        
        log_debug "  Extracted values from $filename:"
        log_debug "    Port: $legacy_port"
        log_debug "    Algorithm: $legacy_algo"
        log_debug "    Difficulty: $legacy_difficulty"
        log_debug "    Max TTF: $legacy_max_ttf"
        
        # Calculate new port with offset
        if [ -n "$legacy_port" ]; then
            new_port=$((legacy_port + PORT_OFFSET))
        else
            log_warn "  Could not extract port from $filename, skipping"
            continue
        fi
        
        # Use defaults if values not found
        [ -z "$legacy_difficulty" ] && legacy_difficulty="128"
        [ -z "$legacy_max_ttf" ] && legacy_max_ttf="40000"
        
        # Generate yiimp2 stratum config
        cat > "$yiimp2_config" << STRATUMEOF
[TCP]
server = 0.0.0.0
port = 3333
password = yiimp2stratum

[SQL]
host = ${DB_HOST}
database = ${DB_NAME}
username = ${DB_USER}
password = ${DB_PASS}

[STRATUM]
algo = ${legacy_algo}
difficulty = ${legacy_difficulty}
max_ttf = ${legacy_max_ttf}

STRATUMEOF
        
        # Set secure permissions (contains database password)
        chmod 600 "$yiimp2_config"
        
        log_info "  ✓ Created: $yiimp2_config"
        log_info "    Legacy port: $legacy_port -> Yiimp2 port: $new_port (internal: 3333)"
        log_info "    Algorithm: $legacy_algo, Difficulty: $legacy_difficulty"
    done
    
    log_info "✓ Processed $STRATUM_COUNTER stratum configuration(s)"
fi

# Calculate duration
END_TIME=$(date +%s)
DURATION=$((END_TIME - START_TIME))

# Log summary
log_info "========================================="
log_info "Configuration generation complete!"
log_info "========================================="
log_info "Summary:"
log_info "  Duration: ${DURATION}s"
log_info ""
log_info "Generated files:"
log_info "  - ${YIIMP2_CONFIG_DIR}/serverconfig.php (permissions: 600)"
if [ -d "$LEGACY_STRATUM_DIR" ]; then
    log_info "  - $STRATUM_COUNTER stratum configs in ${YIIMP2_STRATUM_DIR}/ (permissions: 600)"
fi
log_info ""
log_info "Database Configuration:"
log_info "  Host: ${DB_HOST}"
log_info "  Database: ${DB_NAME}"
log_info "  User: ${DB_USER}"
log_info ""
log_info "Port Configuration:"
log_info "  Port offset: ${PORT_OFFSET}"
log_info "  Web frontend: 8090 (mapped from container port 80)"
log_info "  Stratum servers: Use Docker Compose port mappings"
log_info ""
log_info "Next steps:"
log_info "  1. Review generated configurations in ${YIIMP2_CONFIG_DIR}/"
log_info "  2. Update docker-compose.yml with port mappings"
log_info "  3. Run: docker compose up -d"
log_info ""
log_info "Log file: $LOG_FILE"

# Write summary to log file
cat >> "$LOG_FILE" << EOF

================================================================================
Configuration Generation Summary
================================================================================
Status: SUCCESS
End Time: $(date)
Duration: ${DURATION}s
Generated Files:
  - serverconfig.php
  - $STRATUM_COUNTER stratum configuration(s)
Database: $DB_NAME @ $DB_HOST
User: $DB_USER
Port Offset: $PORT_OFFSET
================================================================================
EOF
